import assert from 'node:assert/strict';
import {performance,monthRange,actionCreated,inRange} from '../app/lib/ui-model.ts';
const now='2026-10-26';const start='2026-10-26',end='2026-11-01';
const visits=[{id:'done',status:'completed',plannedDate:now},{id:'waiting',status:'planned',plannedDate:now},{id:'future',status:'planned',plannedDate:'2026-10-27'},{id:'cancel',status:'cancelled',plannedDate:now},{id:'unplanned',status:'completed',plannedDate:null},{id:'old',status:'completed',plannedDate:'2026-10-25'}];
assert.deepEqual(performance(visits,start,end,now),{total:2,done:1,rate:50});
assert.deepEqual(performance([],start,end,now),{total:0,done:0,rate:null});
assert.deepEqual(performance(visits.filter(v=>v.id==='future'),start,end,now),{total:0,done:0,rate:null});
assert.deepEqual(monthRange('2024-02-14'),['2024-02-01','2024-02-29']);
assert.deepEqual(monthRange('2026-12-31'),['2026-12-01','2026-12-31']);
assert.equal(actionCreated('a',[]),null);
assert.equal(actionCreated('a',[{entityId:'a',before:'{}',createdAt:'2026-10-27T12:00:00Z'},{entityId:'a',before:null,createdAt:'2026-10-26T12:00:00Z'}]),'2026-10-26');
assert.equal(inRange('2026-10-26',start,end),true);assert.equal(inRange('2026-10-25',start,end),false);
console.log('9 UI metric assertions passed: cohort completion, empty/future plans, calendar boundaries, and evidence-based issue dates.');
