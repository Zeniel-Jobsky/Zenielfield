import assert from 'node:assert/strict';
import {dayShift,daysBetween,weekRange,monthRange,mmdd,validDay,between} from '../app/lib/date.ts';
// 날짜 공통 함수(lib/date.ts): 월말·윤년·주 경계·null
assert.equal(dayShift('2024-02-28',1),'2024-02-29');assert.equal(dayShift('2026-03-01',-1),'2026-02-28');
assert.equal(daysBetween('2026-10-01','2026-10-29'),28);assert.equal(daysBetween(null,'2026-10-29'),null);
assert.deepEqual(weekRange('2026-11-01'),['2026-10-26','2026-11-01']);assert.deepEqual(monthRange('2024-02-10'),['2024-02-01','2024-02-29']);
assert.equal(mmdd('2026-10-04'),'10.04');assert.equal(validDay('2026-02-30'),false);assert.equal(between(null,'a','b'),false);
import {nextDue,visitState,canSite,siteState,week} from '../app/lib/model.ts';
assert.equal(nextDue('2026-01-31','monthly'),'2026-02-28');
assert.equal(nextDue('2024-01-31','monthly'),'2024-02-29');
assert.equal(nextDue('2026-11-30','quarterly'),'2027-02-28');
assert.equal(nextDue('2026-10-20','weekly'),'2026-10-27');
assert.equal(nextDue(null,'monthly'),null);
assert.equal(nextDue('2026-10-01','manual'),null);
assert.deepEqual(week('2026-11-01'),['2026-10-26','2026-11-01']);
const v={status:'planned',plannedDate:'2026-10-25'};
assert.equal(visitState(v,'2026-10-26'),'지연');
assert.equal(visitState({...v,status:'cancelled'},'2026-10-26'),'취소');
assert.equal(visitState({...v,status:'completed'},'2026-10-26'),'완료');
assert.equal(visitState({...v,plannedDate:'2026-10-26'},'2026-10-26'),'예정');
const s={id:'s1',team:'A',part:'B',cycle:'monthly',status:'운영 중'};
const user={id:'u1',role:'manager',team:'A',part:'B'};
assert.equal(canSite(user,s,[{siteId:'s1',userId:'u1',endDate:null}]),true);
assert.equal(canSite(user,s,[{siteId:'s1',userId:'u1',endDate:'2026-10-25'}]),false);
assert.equal(canSite({...user,role:'lead',team:'C'},s,[]),false);
assert.equal(canSite({...user,role:'partlead',part:'C'},s,[]),false);
assert.equal(siteState(s,[],'2026-10-26'),'이력 미확인');
assert.equal(siteState(s,[{siteId:'s1',status:'completed',actualDate:'2026-09-25'}],'2026-10-26'),'방문 도래');
assert.equal(siteState(s,[{siteId:'s1',status:'completed',actualDate:'2026-10-25'}],'2026-10-26'),'계획 없음');
console.log('20 date, state and authorization assertions passed.');
